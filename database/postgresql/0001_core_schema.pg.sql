SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SET client_min_messages = warning;

-- funcao usada pelos gatilhos de updated_at (equivale ao ON UPDATE do MySQL)
CREATE OR REPLACE FUNCTION somase_set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS "roles" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "slug" varchar(50) NOT NULL UNIQUE,
    "name" varchar(100) NOT NULL,
    "is_system" smallint NOT NULL DEFAULT 0,
    "created_at" timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "permissions" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "slug" varchar(100) NOT NULL UNIQUE,
    "name" varchar(150) NOT NULL,
    "group_name" varchar(50),
    "created_at" timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "role_permissions" (
    "role_id" integer NOT NULL,
    "permission_id" integer NOT NULL,
    PRIMARY KEY ("role_id", "permission_id"),
    CONSTRAINT "fk_rp_role" FOREIGN KEY ("role_id") REFERENCES "roles" ("id") ON DELETE CASCADE,
    CONSTRAINT "fk_rp_permission" FOREIGN KEY ("permission_id") REFERENCES "permissions" ("id") ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "users" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name" varchar(255) NOT NULL,
    "email" varchar(255) NOT NULL UNIQUE,
    "password" varchar(255) NOT NULL,
    "role_id" integer NOT NULL,
    "status" varchar(12) NOT NULL DEFAULT 'active' CHECK ("status" IN ('active', 'inactive')),
    "last_login_at" timestamp,
    "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
    "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "fk_users_role" FOREIGN KEY ("role_id") REFERENCES "roles" ("id")
);
DROP TRIGGER IF EXISTS "trg_users_updated_at" ON "users";
CREATE TRIGGER "trg_users_updated_at" BEFORE UPDATE ON "users" FOR EACH ROW EXECUTE FUNCTION somase_set_updated_at();

CREATE INDEX IF NOT EXISTS "idx_email" ON "users" ("email");

CREATE TABLE IF NOT EXISTS "tenants" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name" varchar(255) NOT NULL,
    "slug" varchar(100) NOT NULL UNIQUE,
    "status" varchar(12) NOT NULL DEFAULT 'active' CHECK ("status" IN ('active', 'inactive')),
    "settings_json" jsonb,
    "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
    "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP
);
DROP TRIGGER IF EXISTS "trg_tenants_updated_at" ON "tenants";
CREATE TRIGGER "trg_tenants_updated_at" BEFORE UPDATE ON "tenants" FOR EACH ROW EXECUTE FUNCTION somase_set_updated_at();

CREATE TABLE IF NOT EXISTS "user_tenants" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user_id" integer NOT NULL,
    "tenant_id" integer NOT NULL,
    "role_id" integer NOT NULL,
    "active" smallint NOT NULL DEFAULT 1,
    "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "uq_user_tenant" UNIQUE ("user_id", "tenant_id"),
    CONSTRAINT "fk_ut_user" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE,
    CONSTRAINT "fk_ut_tenant" FOREIGN KEY ("tenant_id") REFERENCES "tenants" ("id") ON DELETE CASCADE,
    CONSTRAINT "fk_ut_role" FOREIGN KEY ("role_id") REFERENCES "roles" ("id")
);

